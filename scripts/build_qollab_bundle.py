"""Generate qollab/ -- the self-contained Qollab (Pyodide, no torch) project that gets uploaded.

    PYTHONPATH=$PWD python scripts/build_qollab_bundle.py

qollab/main.py and qollab/README.md are hand-written; everything else is regenerated here from the
repo so the bundle never drifts:
  genqai/*.py                      the modules the inference + scoring + measurement path imports
  checkpoints/<sys>/sft.json+.bin  NumPy export of checkpoints/<sys>/sft.pt (genqai.infer_numpy)
  data/<sys>/hamiltonians.jsonl    stored grid Hamiltonians (train/val labels' features, fallback)
  data/<sys>/teacher*.jsonl        TRAIN-split labels only (what nn_reuse_gauge / angle_regression read)
  data/results_summary.json        held-out test metrics from results/ and results_fresh/ (context)
  datafiles.py                     every data path as a literal string (Qollab only ships data files
                                   whose path appears literally in Python source)
  requirements.txt
Qollab limits: <= 100 files, <= 2 MB per file (checked at the end).
"""
import json
import shutil
from pathlib import Path

from genqai.data import FRESH_SPLIT, load_hamiltonians, load_teacher, results_dir
from genqai.evaluate import summarize
from genqai.infer_numpy import export_numpy
from genqai.schema import EvalRecord, dump_jsonl, load_jsonl

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "qollab"
SYSTEMS = ("h2", "lih4", "h4", "lih6")
MODULES = ("__init__", "adapt", "baselines", "chemistry", "circuits", "data", "demo", "evaluate", "features",
           "infer_numpy", "measure", "pool", "regression", "schema", "sim")
SUMMARY_METHODS = ("sft_oneshot", "angle_regression", "nn_reuse_gauge", "adapt", "ccsd", "hf")
REQUIREMENTS = """\
# Qollab: also enable the "Qiskit Nature (+ PySCF)" library (live Hamiltonians for any geometry).
# qiskit, numpy, scipy, matplotlib are provided by the runtime / Pyodide.
qiskit-nature==0.8.0
pyscf>=2.14.0,<3
scikit-learn
"""
MAX_FILE_BYTES = 2 * 1024 * 1024
MAX_FILES = 100


def _results_summary() -> dict:
    """{system: {split_set: {method: stats}}} on held-out test geometries only."""
    out = {}
    for s in SYSTEMS:
        out[s] = {}
        for fresh, split in ((True, FRESH_SPLIT), (False, "test")):
            rows = []
            for m in SUMMARY_METHODS:
                p = results_dir(fresh) / s / f"{m}.jsonl"
                if p.exists():
                    rows += load_jsonl(p, EvalRecord)
            stats = summarize(rows)
            out[s][split] = {m: {k: stats[m][split][k] for k in (
                "n", "median_abs_err_mha", "frac_under_1.6mha", "mean_cnot_count",
                "mean_pool_gradient_evals", "mean_energy_evals")} for m in stats if split in stats[m]}
    return out


def build() -> list[Path]:
    for sub in ("genqai", "data", "checkpoints"):
        shutil.rmtree(OUT / sub, ignore_errors=True)
    (OUT / "genqai").mkdir(parents=True)
    written = []
    for m in MODULES:
        dst = OUT / "genqai" / f"{m}.py"
        shutil.copyfile(ROOT / "genqai" / f"{m}.py", dst)
        written.append(dst)
    data = []
    for s in SYSTEMS:
        data += export_numpy(ROOT / "checkpoints" / s / "sft.pt", OUT / "checkpoints" / s / "sft.json")
        d = OUT / "data" / s
        d.mkdir(parents=True)
        shutil.copyfile(ROOT / "data" / s / "hamiltonians.jsonl", d / "hamiltonians.jsonl")
        train_ids = [r.geometry_id for r in load_hamiltonians(s, "train")]
        teacher, canon = load_teacher(s), load_teacher(s, "teacher_canonical")
        slim = []
        for g in train_ids:
            c = teacher[g]
            c.meta = {k: v for k, v in c.meta.items() if k != "steps"}  # per-step ADAPT log not needed
            slim.append(c)
        dump_jsonl(slim, d / "teacher.jsonl")
        dump_jsonl([canon[g] for g in train_ids], d / "teacher_canonical.jsonl")
        data += [d / "hamiltonians.jsonl", d / "teacher.jsonl", d / "teacher_canonical.jsonl"]
    summary = OUT / "data" / "results_summary.json"
    summary.write_text(json.dumps(_results_summary(), indent=1))
    data.append(summary)
    written += data
    lines = ",\n".join(f'    "{p.relative_to(OUT).as_posix()}"' for p in data)
    (OUT / "datafiles.py").write_text(
        '"""GENERATED by scripts/build_qollab_bundle.py. Every data file as a literal path: Qollab only\n'
        'ships data files whose path appears as a literal string in Python source."""\n\n'
        f"DATA_FILES = (\n{lines},\n)\n")
    (OUT / "requirements.txt").write_text(REQUIREMENTS)
    return written


def check() -> None:
    files = [p for p in OUT.rglob("*") if p.is_file() and "__pycache__" not in p.parts]
    big = [(p, p.stat().st_size) for p in files if p.stat().st_size > MAX_FILE_BYTES]
    if big or len(files) >= MAX_FILES:
        raise SystemExit(f"Qollab limits violated: {len(files)} files, over 2 MB: {big}")
    src = "\n".join(p.read_text() for p in files if p.suffix == ".py")
    missing = [p for p in files if p.suffix not in (".py", ".md", ".txt", ".png")
               and f'"{p.relative_to(OUT).as_posix()}"' not in src]
    if missing:
        raise SystemExit(f"data files without a literal path in Python source: {missing}")
    total = sum(p.stat().st_size for p in files)
    print(f"qollab/: {len(files)} files, {total / 1e6:.2f} MB total, largest "
          f"{max(p.stat().st_size for p in files) / 1e6:.2f} MB")


if __name__ == "__main__":
    build()
    check()
