"""Workbench exports (Lane E): reproducible artifacts for one experiment.

    qiskit_code(record, circuit)      standalone Python script that rebuilds the exact circuit
    qasm(record, circuit, version)    OpenQASM 2/3 after decomposition to the shared CX basis
    hamiltonian_json(record)          the HamiltonianRecord as JSON
    metadata_json(experiment)         config, model, software versions and content hashes
    measurements_csv(execution)       one row per measurement group of an ExecutionRecord
    benchmark_csv(grades)             one row per graded circuit (flattened GradeReport)

Every export is a pure function of its inputs; nothing here runs a quantum computation except the
deterministic transpilation in `qasm`.
"""
from __future__ import annotations

import csv
import dataclasses
import hashlib
import io
import json
import math
from pathlib import Path

import numpy as np

from genqai.circuits import BASIS, build_circuit
from genqai.pool import get_pool
from genqai.schema import GeneratedCircuit, HamiltonianRecord, software_versions


def to_jsonable(obj):
    """Dataclasses, tuples, numpy scalars/arrays and Paths -> plain JSON types (recursively)."""
    if dataclasses.is_dataclass(obj) and not isinstance(obj, type):
        return {f.name: to_jsonable(getattr(obj, f.name)) for f in dataclasses.fields(obj)}
    if isinstance(obj, dict):
        return {str(k): to_jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple, set, frozenset)):
        return [to_jsonable(v) for v in obj]
    if isinstance(obj, np.ndarray):
        return to_jsonable(obj.tolist())
    if isinstance(obj, np.generic):
        return obj.item()
    if isinstance(obj, Path):
        return str(obj)
    return obj


def canonical_json(obj) -> str:
    """Deterministic compact JSON used for hashing."""
    return json.dumps(to_jsonable(obj), sort_keys=True, separators=(",", ":"), allow_nan=True)


def sha256_of(obj) -> str:
    return hashlib.sha256(canonical_json(obj).encode()).hexdigest()


def _check(record: HamiltonianRecord, circuit: GeneratedCircuit) -> None:
    if circuit.system != record.system or circuit.geometry_id != record.geometry_id:
        raise ValueError(f"circuit {circuit.system}/{circuit.geometry_id} does not belong to record "
                         f"{record.system}/{record.geometry_id}")
    if not circuit.valid:
        raise ValueError("circuit is marked invalid; nothing to export")


def qiskit_code(record: HamiltonianRecord, circuit: GeneratedCircuit) -> str:
    """A standalone script (needs only qiskit) that rebuilds `build_circuit(record, ops, angles)` exactly.

    Each generator is written out as SparsePauliOp.from_list with its Pauli labels and real coefficients,
    and every float uses repr(), so the script reproduces the statevector bit-for-bit up to floating point.
    """
    _check(record, circuit)
    pool = get_pool(record.system)
    n = record.num_qubits
    lines = [
        '"""GenQAI circuit export (generated by genqai.export.qiskit_code).',
        "",
        f"system={record.system}  geometry_id={record.geometry_id}  geometry={record.geometry_params}",
        f"source={circuit.source or '-'}  operators={len(circuit.operators)}  qubits={n}",
        "Circuit = HF state, then prod_t exp(-i * angle_t * G_t) in list order (Pauli labels: qubit 0 rightmost).",
        f"FCI reference energy: {record.fci_energy!r} Ha; energy_shift: {record.energy_shift!r} Ha.",
        '"""',
        "from qiskit import QuantumCircuit",
        "from qiskit.circuit.library import PauliEvolutionGate",
        "from qiskit.quantum_info import SparsePauliOp",
        "from qiskit.synthesis import LieTrotter",
        "",
        f"HF_STATE = {record.hf_state!r}",
        f"NUM_QUBITS = {n}",
        "",
        "GENERATORS = [",
    ]
    for t, (k, angle) in enumerate(zip(circuit.operators, circuit.angles)):
        g = pool.generators[k]
        terms = ", ".join(f"({lbl!r}, {float(np.real(c))!r})" for lbl, c in zip(g.paulis.to_labels(), g.coeffs))
        lines.append(f"    # step {t}: operator {k} = {pool.describe(k)}")
        lines.append(f"    (SparsePauliOp.from_list([{terms}]), {float(angle)!r}),")
    lines += [
        "]",
        "",
        "",
        "def build() -> QuantumCircuit:",
        "    qc = QuantumCircuit(NUM_QUBITS)",
        "    for q, bit in enumerate(reversed(HF_STATE)):",
        "        if bit == '1':",
        "            qc.x(q)",
        "    for generator, angle in GENERATORS:",
        "        qc.append(PauliEvolutionGate(generator, time=angle, synthesis=LieTrotter()), range(NUM_QUBITS))",
        "    return qc",
        "",
        "",
        "circuit = build()",
        "",
        "if __name__ == '__main__':",
        "    print(circuit)",
        "",
    ]
    return "\n".join(lines)


def compiled_circuit(record: HamiltonianRecord, circuit: GeneratedCircuit):
    """The circuit decomposed to the shared CX basis (same settings as genqai.measure.compile_state)."""
    from genqai.measure import compile_state

    _check(record, circuit)
    return compile_state(build_circuit(record, circuit.operators, circuit.angles))


def qasm(record: HamiltonianRecord, circuit: GeneratedCircuit, version: int = 3) -> str:
    """OpenQASM 2 or 3 text of the compiled circuit (basis cx, rz, sx, x). Raises if not representable."""
    if version not in (2, 3):
        raise ValueError("version must be 2 or 3")
    qc = compiled_circuit(record, circuit)
    extra = set(qc.count_ops()) - set(BASIS) - {"barrier"}
    if extra:
        raise ValueError(f"compiled circuit still has non-basis gates {sorted(extra)}")
    if version == 2:
        from qiskit import qasm2

        return qasm2.dumps(qc)
    from qiskit import qasm3

    return qasm3.dumps(qc)


def hamiltonian_json(record: HamiltonianRecord) -> str:
    return json.dumps(to_jsonable(record), indent=2)


def metadata_json(experiment: dict) -> str:
    """Experiment metadata: whatever the caller passes (config, method, model card, generation log, ...)
    plus software versions and SHA-256 content hashes of the record, circuits and config.

    Recognised keys for hashing: "config", "record", "circuit", "circuits" (dict or list).
    """
    exp = to_jsonable(experiment)
    hashes = {}
    if "config" in exp:
        hashes["config_sha256"] = sha256_of(exp["config"])
    if exp.get("record") is not None:
        rec = exp["record"]
        hashes["record_sha256"] = sha256_of(rec)
        hashes["hamiltonian_sha256"] = sha256_of({k: rec.get(k) for k in ("num_qubits", "pauli_terms", "energy_shift")})
    if exp.get("circuit") is not None:
        hashes["circuit_sha256"] = sha256_of(_circuit_content(exp["circuit"]))
    circuits = exp.get("circuits")
    if isinstance(circuits, dict):
        hashes["circuits_sha256"] = {k: sha256_of(_circuit_content(c)) for k, c in circuits.items()}
    elif isinstance(circuits, list):
        hashes["circuits_sha256"] = [sha256_of(_circuit_content(c)) for c in circuits]
    try:
        versions = software_versions()
    except ImportError as exc:  # e.g. no PySCF in this runtime
        versions = {"error": f"{type(exc).__name__}: {exc}"}
    out = {**exp, "software_versions": exp.get("software_versions") or versions, "hashes": hashes}
    return json.dumps(out, indent=2, sort_keys=True, default=str)


def _circuit_content(c: dict) -> dict:
    """The physical content of a circuit (what it does, not how it was labelled)."""
    return {k: c.get(k) for k in ("system", "geometry_id", "operators", "angles", "valid")}


def _scalar(v):
    if isinstance(v, float) and not math.isfinite(v):
        return str(v)
    if isinstance(v, (dict, list)):
        return json.dumps(v, sort_keys=True)
    return "" if v is None else v


def _flatten(d: dict, prefix: str = "") -> dict:
    out = {}
    for k, v in d.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            out.update(_flatten(v, key + "."))
        else:
            out[key] = _scalar(v)
    return out


def _csv(rows: list[dict], first: tuple[str, ...] = ()) -> str:
    cols = [c for c in first if any(c in r for r in rows)]
    for r in rows:
        cols += [c for c in r if c not in cols]
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=cols, lineterminator="\n")
    w.writeheader()
    for r in rows:
        w.writerow({c: r.get(c, "") for c in cols})
    return buf.getvalue()


EXECUTION_FIELDS = ("execution_id", "backend", "noise_model", "shots", "packed", "num_groups", "width", "energy",
                    "stderr", "error_mha", "job_id", "status", "runtime_s")


def measurements_csv(execution) -> str:
    """ExecutionRecord (dataclass or dict) -> CSV, one row per measurement group (execution fields repeated),
    or a single summary row when the execution has no per-group details."""
    ex = to_jsonable(execution)
    summary = {k: _scalar(ex.get(k)) for k in EXECUTION_FIELDS if k in ex}
    groups = ex.get("group_details") or []
    rows = [{**summary, "group": i, **_flatten(g, "group.")} for i, g in enumerate(groups)] or [summary]
    return _csv(rows, EXECUTION_FIELDS)


def benchmark_csv(grades: dict) -> str:
    """{circuit name: GradeReport (dataclass or dict)} -> CSV, one flattened row per circuit."""
    rows = []
    for name, g in grades.items():
        g = to_jsonable(g)
        row = {"name": name, "status": g.get("status", "")}
        for section in ("checks", "energy", "resources", "cost", "noise"):
            if isinstance(g.get(section), dict):
                row.update(_flatten(g[section], section + "."))
        row["weighted_score"] = _scalar(g.get("weighted_score"))
        rows.append(row)
    return _csv(rows, ("name", "status"))
